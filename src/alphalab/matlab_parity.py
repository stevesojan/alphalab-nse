"""Python twin of matlab/parfor_sweep.m (same simplified EMA-cross backtest) for cross-language checks
and timing, plus the runner that executes MATLAB and compares outputs (python -m alphalab.matlab_parity)."""
from __future__ import annotations

import subprocess
import time
import warnings
from datetime import date
from pathlib import Path

import numpy as np
import polars as pl

from .backtest import metrics as M

ROOT = Path(__file__).resolve().parents[2]
EXPORT = ROOT / "reports" / "study" / "export"
OUT = ROOT / "reports" / "matlab"
MATLAB = Path(r"C:\Program Files\MATLAB\R2026b\bin\matlab.exe")
FASTS = list(range(2, 41, 2))
SLOWS = list(range(50, 301, 25))


def load_wide():
    W = pl.read_parquet(EXPORT / "wide_close.parquet")
    U = pl.read_parquet(EXPORT / "wide_in_universe.parquet")
    dates = W["date"].to_list()
    C = W.drop("date").to_numpy().astype(float)
    Uu = U.drop("date").to_numpy() > 0
    return dates, C, Uu


def ema_nan(X: np.ndarray, span: int) -> np.ndarray:
    a = 2.0 / (span + 1)
    E = np.full_like(X, np.nan)
    prev = np.full(X.shape[1], np.nan)
    for t in range(X.shape[0]):
        x = X[t]
        cur = prev.copy()
        seed = np.isnan(prev) & ~np.isnan(x)
        upd = ~np.isnan(prev) & ~np.isnan(x)
        cur[seed] = x[seed]
        cur[upd] = a * x[upd] + (1 - a) * prev[upd]
        E[t] = cur
        prev = cur
    return E


def sim_one(ef, es, Uu, R, keep) -> float:
    a = ef / es - 1
    a[~Uu | ~np.isfinite(a)] = np.nan
    with warnings.catch_warnings():              # dates before the universe warm-up are all-NaN rows
        warnings.simplefilter("ignore", RuntimeWarning)
        a = a - np.nanmean(a, axis=1, keepdims=True)
    g = np.nansum(np.abs(a), axis=1, keepdims=True)
    with np.errstate(invalid="ignore", divide="ignore"):
        w = a / g
    w[~np.isfinite(w)] = 0.0
    pnl = np.zeros(len(w))
    gross = np.zeros(len(w))
    pnl[2:] = (w[:-2] * R[2:]).sum(axis=1)
    gross[2:] = np.abs(w[:-2]).sum(axis=1)
    x = pnl[keep & (gross > 0)]
    return float(x.mean() / x.std(ddof=1) * np.sqrt(252))


def sweep() -> tuple[pl.DataFrame, float]:
    dates, C, Uu = load_wide()
    with np.errstate(invalid="ignore", divide="ignore"):
        R = np.vstack([np.full((1, C.shape[1]), np.nan), C[1:] / C[:-1] - 1])
    R[np.isnan(R)] = 0.0
    keep = np.array([d >= date(2015, 1, 1) for d in dates])
    E = {s: ema_nan(C, s) for s in sorted(set(FASTS) | set(SLOWS))}
    t = time.perf_counter()
    rows = [(f, s, sim_one(E[f], E[s], Uu, R, keep)) for s in SLOWS for f in FASTS]
    return pl.DataFrame(rows, schema=["fast", "slow", "sharpe"], orient="row"), time.perf_counter() - t


def run_matlab() -> float:
    t = time.perf_counter()
    cmd = [str(MATLAB), "-batch", f"cd('{(ROOT / 'matlab').as_posix()}'); run_all"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    (OUT / "matlab_stdout.txt").write_text(r.stdout + "\n" + r.stderr, encoding="utf-8")
    if r.returncode != 0:
        raise RuntimeError(f"MATLAB failed ({r.returncode}):\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    return time.perf_counter() - t


def compare() -> str:
    """Compare MATLAB outputs with Python; returns a markdown report and writes MATLAB_RESULTS.md."""
    L = ["# MATLAB cross-check (Phase 7)", "", "Generated by `python -m alphalab.matlab_parity` "
         "(runs `matlab -batch run_all`, then compares with Python).", ""]
    env = (OUT / "environment.txt").read_text(encoding="utf-8").splitlines()
    L += ["## Environment", "", "```", *env[:4], "```", ""]
    # 1) six metrics
    mt = pl.read_csv(OUT / "crosscheck_metrics.csv")
    L += ["## 1. Six metrics: MATLAB vs Python on identical daily PnL", "",
          "| family | Sharpe (MATLAB) | max abs diff over the 6 metrics |", "|---|---|---|"]
    worst = 0.0
    for r in mt.iter_rows(named=True):
        d = pl.read_parquet(EXPORT / f"daily_{r['family']}.parquet").filter(pl.col("gross") > 0)
        py = M.summary(d["pnl"].to_numpy(), d["traded"].to_numpy())
        diff = max(abs(py[k] - r[k]) for k in ("sharpe", "turnover", "fitness", "returns", "drawdown", "margin_bps"))
        worst = max(worst, diff)
        L.append(f"| {r['family']} | {r['sharpe']:.4f} | {diff:.2e} |")
    L += ["", f"**Worst difference: {worst:.2e}** (tolerance 1e-6): {'PASS' if worst < 1e-6 else 'FAIL'}", ""]
    # 2) bootstrap
    bt = pl.read_csv(OUT / "bootstrap_sharpe.csv")
    L += ["## 2. Sharpe confidence intervals (full sample, gross)", "",
          "| family | Sharpe | i.i.d. bootci 95% | moving-block (20d) 95% |", "|---|---|---|---|"]
    for r in bt.iter_rows(named=True):
        L.append(f"| {r['family']} | {r['sharpe']:.2f} | [{r['iid_lo']:.2f}, {r['iid_hi']:.2f}] | [{r['block_lo']:.2f}, {r['block_hi']:.2f}] |")
    # 3) regimes
    rg = pl.read_csv(OUT / "regime_sharpe.csv")
    L += ["", "## 3. Volatility regimes (Gaussian mixture on log 21-day market vol; descriptive, full-sample labels)", "",
          "| family | Sharpe, low-vol days | Sharpe, high-vol days | low days | high days |", "|---|---|---|---|---|"]
    for r in rg.iter_rows(named=True):
        L.append(f"| {r['family']} | {r['sharpe_low_vol']:.2f} | {r['sharpe_high_vol']:.2f} | {r['days_low']} | {r['days_high']} |")
    L += ["", "Figure: `regimes.png`.", ""]
    # 4) parfor sweep parity + timing
    ml = pl.read_csv(OUT / "parfor_sweep.csv")
    py, t_py = sweep()
    j = ml.join(py, on=["fast", "slow"], suffix="_py")
    dmax = float((j["sharpe"] - j["sharpe_py"]).abs().max())
    tm = pl.read_csv(OUT / "parfor_timing.csv").row(0, named=True)
    L += ["## 4. EMA-cross sweep: serial vs parfor, and MATLAB vs Python (simplified backtest)", "",
          f"- Configurations: {tm['n_configs']} (fast 2..40 step 2 x slow 50..300 step 25).",
          f"- MATLAB serial: {tm['serial_s']:.2f} s; parfor on {tm['workers']} workers: {tm['parfor_s']:.2f} s "
          f"(+ {tm['pool_start_s']:.1f} s one-off pool start); Python/NumPy serial: {t_py:.2f} s.",
          f"- Max |Sharpe(MATLAB) - Sharpe(Python)| over the grid: **{dmax:.2e}** "
          f"({'PASS' if dmax < 1e-6 else 'FAIL'} at 1e-6).",
          f"- Best grid Sharpe {ml['sharpe'].max():.2f}, worst {ml['sharpe'].min():.2f}: the simplified EMA-cross (no sector neutralization, "
          "no decay/truncation, full sample) is shown for parity and speed, not as a result.", "",
          "Figures: `ema_surface_matlab.png` (from the Python ledger), `regimes.png`."]
    md = "\n".join(L) + "\n"
    (OUT / "MATLAB_RESULTS.md").write_text(md, encoding="utf-8")
    return md


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    secs = run_matlab()
    print(f"MATLAB run_all finished in {secs:.0f}s")
    print(compare())


if __name__ == "__main__":
    main()
